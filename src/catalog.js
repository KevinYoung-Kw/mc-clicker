export function topological() {
  const seen = new Set(),
    result = [];
  while (result.length < CATALOG.length) {
    const next = CATALOG.filter(
      (i) => !seen.has(i.id) && i.deps.every((d) => seen.has(d)),
    );
    if (!next.length) throw Error("购买树存在循环");
    next.forEach((i) => {
      seen.add(i.id);
      result.push(i);
    });
  }
  return result;
}
export function ancestors(id, result = new Set()) {
  if (result.has(id)) return result;
  result.add(id);
  ITEMS[id].deps.forEach((d) => ancestors(d, result));
  return result;
}
